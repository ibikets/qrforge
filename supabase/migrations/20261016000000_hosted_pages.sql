-- Qrenuvi: hosted pages (Digital Business Card first). Additive only: no existing table, row or policy is changed
-- except two new columns on plan_limits. Rollback: supabase/rollback/20261016000000_hosted_pages.down.sql
-- Safe ordering: the app reports "not available yet" for hosted pages until this is applied, so migrate first, then deploy.
begin;

-- 1. New resource limits. Prices and existing limits are untouched. Free gets no hosted pages (the static generator is
--    unchanged); Pro 5 and Business 25 are proposals the Owner can change by editing these rows (no deploy needed).
alter table qrforge.plan_limits add column if not exists max_pages integer not null default 0 check (max_pages >= 0);
alter table qrforge.plan_limits add column if not exists max_media_bytes bigint not null default 0 check (max_media_bytes >= 0);
update qrforge.plan_limits set max_pages = 0,  max_media_bytes = 0          where plan = 'free';
update qrforge.plan_limits set max_pages = 5,  max_media_bytes = 26214400   where plan = 'pro';       -- 25 MB
update qrforge.plan_limits set max_pages = 25, max_media_bytes = 104857600  where plan = 'business';  -- 100 MB

-- 2. Pages. public_id is opaque, generated by the server, immutable and never reused (deleted rows keep it: tombstone).
create table if not exists qrforge.pages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('card')),
  title text not null check (char_length(title) between 1 and 80),
  public_id text not null unique check (public_id ~ '^[a-z2-9]{10}$'),
  draft jsonb not null check (jsonb_typeof(draft) = 'object' and octet_length(draft::text) <= 30000),
  draft_version integer not null default 1,
  published_version integer,                                  -- revision number currently live, null = never published
  lifecycle text not null default 'draft' check (lifecycle in ('draft','published','unpublished','archived','deleted')),
  taken_down_at timestamptz,                                  -- staff abuse takedown; blocks public view and republishing
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  deleted_at timestamptz
);
create index if not exists pages_user_idx on qrforge.pages (user_id, updated_at desc);

-- 3. Immutable published snapshots (the only thing the public ever sees).
create table if not exists qrforge.page_revisions (
  page_id uuid not null references qrforge.pages(id) on delete cascade,
  version integer not null,
  content jsonb not null check (octet_length(content::text) <= 30000),
  published_by uuid,
  published_at timestamptz not null default now(),
  primary key (page_id, version)
);

-- 4. Media derivatives. Files live in a PRIVATE bucket; the app streams them through authorised routes.
create table if not exists qrforge.page_media (
  id uuid primary key default gen_random_uuid(),
  page_id uuid not null references qrforge.pages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('portrait','logo')),
  path text not null unique,
  vcf_path text unique,                                       -- small JPEG used only inside the downloadable contact file
  mime text not null check (mime in ('image/webp','image/png','image/jpeg')),
  bytes integer not null check (bytes > 0 and bytes <= 2000000),
  vcf_bytes integer not null default 0,
  width integer not null,
  height integer not null,
  created_at timestamptz not null default now()
);
create index if not exists page_media_page_idx on qrforge.page_media (page_id);

-- 5. Deny by default: browsers (anon / signed-in users) cannot touch these tables at all. Every read and write goes through
--    server routes that authenticate the user and filter by owner; RLS stays on as a second lock.
alter table qrforge.pages enable row level security;
alter table qrforge.page_revisions enable row level security;
alter table qrforge.page_media enable row level security;
revoke all on qrforge.pages, qrforge.page_revisions, qrforge.page_media from anon, authenticated;
grant select, insert, update, delete on qrforge.pages, qrforge.page_revisions, qrforge.page_media to service_role;

-- 6. Entitlements where the data lives (same pattern as saved codes): per-user advisory lock, then count.
create or replace function qrforge.active_plan(p_user uuid) returns text
language sql stable security definer set search_path = pg_catalog, qrforge as $$
  select coalesce((select s.plan from qrforge.subscriptions s where s.user_id = p_user and s.current_period_end > now()), 'free')
$$;
revoke all on function qrforge.active_plan(uuid) from public, anon, authenticated;

create or replace function qrforge.enforce_page_quota() returns trigger
language plpgsql security definer set search_path = pg_catalog, qrforge as $$
declare v_lim qrforge.plan_limits%rowtype; v_count integer;
begin
  perform pg_advisory_xact_lock(hashtextextended('qrforge.pages:' || NEW.user_id::text, 0));
  select * into v_lim from qrforge.plan_limits where plan = qrforge.active_plan(NEW.user_id);
  select count(*) into v_count from qrforge.pages where user_id = NEW.user_id and lifecycle <> 'deleted';
  if v_count >= v_lim.max_pages then
    raise exception 'hosted page limit reached for plan %', qrforge.active_plan(NEW.user_id) using errcode = 'QF010', hint = 'limit=' || v_lim.max_pages;
  end if;
  return NEW;
end $$;
revoke all on function qrforge.enforce_page_quota() from public, anon, authenticated;
drop trigger if exists pages_quota on qrforge.pages;
create trigger pages_quota before insert on qrforge.pages for each row execute function qrforge.enforce_page_quota();

create or replace function qrforge.enforce_media_quota() returns trigger
language plpgsql security definer set search_path = pg_catalog, qrforge as $$
declare v_lim qrforge.plan_limits%rowtype; v_bytes bigint; v_n integer;
begin
  perform pg_advisory_xact_lock(hashtextextended('qrforge.media:' || NEW.user_id::text, 0));
  select * into v_lim from qrforge.plan_limits where plan = qrforge.active_plan(NEW.user_id);
  select coalesce(sum(bytes + vcf_bytes), 0), count(*) filter (where page_id = NEW.page_id) into v_bytes, v_n
    from qrforge.page_media where user_id = NEW.user_id;
  if v_n >= 8 then raise exception 'too many images on this page' using errcode = 'QF012'; end if;
  if v_bytes + NEW.bytes + NEW.vcf_bytes > v_lim.max_media_bytes then
    raise exception 'media storage limit reached' using errcode = 'QF011', hint = 'limit=' || v_lim.max_media_bytes;
  end if;
  return NEW;
end $$;
revoke all on function qrforge.enforce_media_quota() from public, anon, authenticated;
drop trigger if exists page_media_quota on qrforge.page_media;
create trigger page_media_quota before insert on qrforge.page_media for each row execute function qrforge.enforce_media_quota();

-- 7. Publish atomically: ownership + version check + entitlement + revision + pointer swap in one transaction.
create or replace function qrforge.publish_page(p_page uuid, p_user uuid, p_expected integer, p_content jsonb)
returns integer language plpgsql security definer set search_path = pg_catalog, qrforge as $$
declare v_page qrforge.pages%rowtype; v_next integer; v_lim qrforge.plan_limits%rowtype;
begin
  select * into v_page from qrforge.pages where id = p_page and user_id = p_user for update;
  if not found then raise exception 'page not found' using errcode = 'QF020'; end if;
  if v_page.lifecycle in ('deleted','archived') then raise exception 'page cannot be published' using errcode = 'QF021'; end if;
  if v_page.taken_down_at is not null then raise exception 'page is disabled' using errcode = 'QF022'; end if;
  if v_page.draft_version <> p_expected then raise exception 'draft changed' using errcode = 'QF023'; end if;
  select * into v_lim from qrforge.plan_limits where plan = qrforge.active_plan(p_user);
  if v_lim.max_pages = 0 then raise exception 'plan does not include hosted pages' using errcode = 'QF024'; end if;
  select coalesce(max(version), 0) + 1 into v_next from qrforge.page_revisions where page_id = p_page;
  insert into qrforge.page_revisions (page_id, version, content, published_by) values (p_page, v_next, p_content, p_user);
  update qrforge.pages set published_version = v_next, lifecycle = 'published', published_at = now(), updated_at = now() where id = p_page;
  delete from qrforge.page_revisions where page_id = p_page and version <= v_next - 20;
  return v_next;
end $$;
revoke all on function qrforge.publish_page(uuid, uuid, integer, jsonb) from public, anon, authenticated;
grant execute on function qrforge.publish_page(uuid, uuid, integer, jsonb) to service_role;

-- 8. Private media bucket (skipped where the storage schema does not exist, e.g. the embedded test database).
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
      values ('page-media', 'page-media', false, 2000000, array['image/webp','image/jpeg','image/png'])
      on conflict (id) do update set public = false;
  end if;
end $$;

commit;
